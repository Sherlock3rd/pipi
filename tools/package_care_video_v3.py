def main():
    manifest={'status':'inputs-awaiting-video-generation','identity':identity,'anchors':{},'actions':[]}
    for key,name in anchors.items():
        p=OUT/'anchors'/name
        with Image.open(p) as im: assert im.size==(1672,941),(name,im.size)
        manifest['anchors'][key]={'file':'anchors/'+name,'sha256':hashlib.sha256(p.read_bytes()).hexdigest()}
    lines=['# 陈皮照料与互动动画制作包 v3','','每个编号文件夹上传首帧.png与尾帧.png，复制提示词.txt全文。编号接续上一批21条。优先22—36，再37—51。',
    '', '过渡建议2秒、循环建议4秒；如平台只支持5秒，用5秒生成并保留原片，返片后再裁掉停留。不要自行加速、镜像、补帧或独立裁切首尾图。输出最高可用质量，保持输入宽高比。',
    '', '本轮照料动作先用右向标准姿态；接入时通过已有真实转身对齐，不镜像生成左侧。左向抓棒和回头另有独立输入。道具全部由程序叠加，视频只生成猫。',
    '', '共享接缝：吃饭22→23循环→24；喝水22→25循环→24；如厕26→27循环→28→29→30循环→31；右抓棒29→35循环→31；左抓棒36循环；拎起32→33循环→34；翻身40→41循环→42。已有06/07负责正面坐姿与右站姿连接，08/09负责左侧。',
    '', '循环首尾使用同一张图是有意的，动画动作发生在中间。22/24和29/31只需各生成一次，多个行为复用。所有共享端点按原字节复制，避免二次生成引入接缝变化。',
    '', identity, '', '| 编号动作 | 首尾 | 类型 | 关键词 |','|---|---|---|---|']
    for folder,a,b,kind,kw,motion in rows:
        d=OUT/folder;d.mkdir(parents=True,exist_ok=True)
        for filename,key in [('首帧.png',a),('尾帧.png',b)]:
            shutil.copy2(OUT/'anchors'/anchors[key],d/filename)
            assert hashlib.sha256((d/filename).read_bytes()).hexdigest()==manifest['anchors'][key]['sha256']
        timing = ('建议4秒完成循环；首尾姿态、位置、大小、速度相位相接，不额外冻结；循环过程中不回到其他站坐姿。' if kind=='循环' else '建议2秒完成一个连续过渡，起始即行动，结束立即可接下一段；不额外安排站定等待。若平台只能5秒，不要添加其他动作，保留原片供后续裁剪。')
        (d/'提示词.txt').write_text(prefix+'\n\n'+motion+'\n\n'+timing+'\n',encoding='utf-8')
        (d/'关键词.txt').write_text(kw+'\n',encoding='utf-8')
        manifest['actions'].append({'folder':folder,'start':a,'end':b,'type':kind,'seconds':4 if kind=='循环' else 2})
        lines.append(f'| [{folder}]({folder}/提示词.txt) | {a} → {b} | {kind} | {kw} |')
    lines+=['','## 验收与返片','','先试22、23、25、32：检查低头口鼻高度、咀嚼与舔水区别、悬空四肢是否稳定，再批量生成。按编号与动作名返还MP4。新关键帧已静态查看；中间动作尚未生成，不代表动画已通过。当前程序未因本制作包而替换素材，边缘锯齿修复仍待单独处理。']
    (OUT/'README.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    (OUT/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    cards=''.join(f'<figure><img src="anchors/{html.escape(name)}"><figcaption>{html.escape(name[:-4])}</figcaption></figure>' for name in anchors.values())
    table=''.join(f'<tr><td>{html.escape(folder)}</td><td>{a} → {b}</td><td>{kind}</td><td><a href="{folder}/首帧.png">首帧</a> · <a href="{folder}/尾帧.png">尾帧</a> · <a href="{folder}/提示词.txt">提示词</a></td></tr>' for folder,a,b,kind,kw,motion in rows)
    page='<!doctype html><meta charset="utf-8"><title>陈皮照料互动视频包</title><style>body{font:16px/1.7 system-ui;background:#eeece6;color:#303431;max-width:1120px;margin:32px auto;padding:20px}h1{font-size:28px}.grid{display:grid;grid-template-columns:repeat(2,1fr);gap:16px}figure{margin:0;background:white;border-radius:14px;overflow:hidden}img{width:100%;display:block}figcaption{padding:8px 16px}table{width:100%;border-collapse:collapse}td,th{text-align:left;border-bottom:1px solid #ccc;padding:9px}a{color:#376a60}@media(max-width:650px){.grid{grid-template-columns:1fr}}</style><h1>陈皮 · 照料与互动动画</h1><p>30条视频 · 8张共用关键帧 · 每条均有首尾图与完整提示词</p><p>先做22、23、25、32。过渡建议2秒，循环建议4秒；平台只支持5秒也可以，返还原片供裁剪。上传每个文件夹的首尾图，复制提示词全文。保持原比例，不独立裁图。</p><p>吃饭22→23→24；喝水22→25→24；如厕26→27→28→29→30→31；右抓棒29→35→31；拎起32→33→34；翻身40→41→42。共用段不重复生成。圈内循环可重复播放。</p><p>保留自身左眼稍小；视频只画猫，不带盆、猫粮、人手、羽毛或特效。<a href="README.md">完整制作说明</a></p><div class="grid">'+cards+'</div><h2>逐条制作</h2><table><tr><th>动作</th><th>接缝</th><th>类型</th><th>文件</th></tr>'+table+'</table><p>新图为静态视频输入；中间动画等待返片检查。当前运行素材未改变，锯齿修复另行处理。</p>'
    (OUT/'index.html').write_text(page,encoding='utf-8')
    archive=OUT.parent/'陈皮-照料互动动画-v3.zip'
    with zipfile.ZipFile(archive,'w',zipfile.ZIP_DEFLATED) as z:
        for p in OUT.rglob('*'):
            if p.is_file(): z.write(p,p.relative_to(OUT))
    with zipfile.ZipFile(archive) as z: assert z.testzip() is None
    print(f'PASS {len(anchors)} anchors, {len(rows)} actions, {len(rows)*2} endpoint hashes, ZIP CRC; {archive}')

if __name__=='__main__': main()
